import base64, json
idx = json.load(open('out/models.json'))
b64 = base64.b64encode(open('out/models.bin','rb').read()).decode()
anim = json.load(open('out/anim.json'))
anim64 = base64.b64encode(open('out/anim.bin','rb').read()).decode()
js = """// Generated by art/build_art.py (Blender). Do not edit by hand.
// Each entry: [vertex count, index count, position scale, byte offset].
// A vertex is 15 bytes: position (3 x int16), normal (3 x int8), colour with
// baked shading (3 x uint8), tint, glow, bone.
const MODEL_INDEX = %s;
const MODEL_DATA = "%s";
// Skeletal animation. ANIM_INDEX names each rig's clips as [first row, frames,
// loops?]; ANIM_DATA holds, per frame and bone, a quaternion and a shift (int16).
const ANIM_INDEX = %s;
const ANIM_DATA = "%s";

return { MODEL_INDEX, MODEL_DATA, ANIM_INDEX, ANIM_DATA };
""" % (json.dumps(idx, separators=(',', ':')), b64, json.dumps(anim, separators=(',', ':')), anim64)
open('src/models.js','w').write(js)
print('models.js', len(js))

import glob, os
t = {}
for f in sorted(glob.glob('out/thumbs/*.webp')):
    t[os.path.basename(f)[:-5]] = 'data:image/webp;base64,' + base64.b64encode(open(f, 'rb').read()).decode()
open('src/thumbs.js', 'w').write("// Generated by art/build_art.py: portraits of each weapon and rank, rendered in Blender.\nconst THUMBS = " + json.dumps(t, indent=0) + ";\n\nreturn { THUMBS };\n")
